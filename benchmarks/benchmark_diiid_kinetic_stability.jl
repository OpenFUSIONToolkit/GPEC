#!/usr/bin/env julia
"""
    benchmark_diiid_kinetic_stability.jl

Benchmark the self-consistent kinetic-DCON path (KF → FFS → PE) against
Fortran GPEC's kinetic DCON reference.

Runs `GPE.main()` with `kinetic_source="calculated"` and `kinetic_factor=1.0`
against the EFIT g-file and `.kin` profile taken from a Fortran GPEC
kinetic example directory, then compares the least-stable total-energy
eigenvalue `vacuum/et[1]` against `W_t_eigenvalue[:, 0]` in the Fortran
`dcon_output_n1.nc`.

No inputs are duplicated into this repo — everything is read from the
Fortran example directory, and the Julia `gpec.toml` is written to a
`mktempdir()` scratch directory at runtime.

Acceptance:
  - Re(et[1]) within 5 %  of Fortran
  - Im(et[1]) within 20 % of Fortran (stretch: 5 %)
Im is the damping-rate component — smaller magnitude, more sensitive to
the non-Hermitian FKG reduction and the inner kinetic-matrix tolerances.

Usage:
    julia --project=. benchmarks/benchmark_diiid_kinetic_stability.jl [fortran_dir]

    fortran_dir defaults to \$GPEC_FORTRAN_DIIID_DCON or
    ~/Code/gpec/docs/examples/DIIID_kinetic_example.
"""

using Printf
using HDF5
using NCDatasets

using GeneralizedPerturbedEquilibrium
const GPE = GeneralizedPerturbedEquilibrium
const AnalysisFFS = GPE.Analysis.ForceFreeStates

const DEFAULT_FORTRAN_DIR = expanduser("~/Code/gpec/docs/examples/DIIID_kinetic_example")

"""
    discover_inputs(fortran_dir) → (; eq_file, kin_file, dcon_nc)

Locate the EFIT g-file, its sibling `.kin` kinetic profile, and the
Fortran `dcon_output_n1.nc` reference NetCDF inside a Fortran GPEC
kinetic example directory. Errors if any required file is missing or if
the g-file cannot be uniquely identified.
"""
function discover_inputs(fortran_dir::String)
    isdir(fortran_dir) || error("Fortran example directory not found: $fortran_dir")
    # EFIT g-files start with "g" followed by a digit; exclude .kin, backups,
    # and gpec_* output files.
    eq_candidates = filter(readdir(fortran_dir)) do f
        length(f) >= 2 && f[1] == 'g' && isdigit(f[2]) &&
            !endswith(f, ".kin") && !endswith(f, ".bak") &&
            !startswith(f, "gpec_")
    end
    length(eq_candidates) == 1 ||
        error("Expected exactly one EFIT g-file in $fortran_dir; found: $eq_candidates")
    eq_file = joinpath(fortran_dir, eq_candidates[1])
    kin_file = eq_file * ".kin"
    dcon_nc = joinpath(fortran_dir, "dcon_output_n1.nc")
    for (label, path) in [("kinetic profile", kin_file),
        ("dcon NetCDF", dcon_nc)]
        isfile(path) || error("$label not found: $path")
    end
    return (; eq_file, kin_file, dcon_nc)
end

"""
    read_dcon_reference(dcon_nc) → NamedTuple

Read the Fortran kinetic-DCON least-stable total-energy eigenvalue from
`dcon_output_n1.nc`. Also returns the plasma and vacuum least-stable
eigenvalues for diagnostic printout (the three are *separately*
diagonalised matrices in DCON, so they do not sum to the total — the
partition is informational only).

NetCDF layout (dims in Fortran order, preserved by NCDatasets):
W_t_eigenvalue(mode, i)   — total    energy, i=1 real, i=2 imag
W_p_eigenvalue(mode, i)   — plasma   energy
W_v_eigenvalue(mode, i)   — vacuum   energy
Mode index 1 is the least-stable mode.
"""
function read_dcon_reference(dcon_nc::String)
    NCDatasets.Dataset(dcon_nc, "r") do ds
        Wt = Array(ds["W_t_eigenvalue"][:, :])
        Wp = Array(ds["W_p_eigenvalue"][:, :])
        Wv = Array(ds["W_v_eigenvalue"][:, :])
        return (
            W_t_re=Wt[1, 1], W_t_im=Wt[1, 2],
            W_p_re=Wp[1, 1], W_p_im=Wp[1, 2],
            W_v_re=Wv[1, 1], W_v_im=Wv[1, 2]
        )
    end
end

"""
    build_benchmark_tomldir(eq_file, kin_file) → tmpdir

Construct a temporary directory containing a Julia `gpec.toml` with
kinetic-DCON settings that mirror the Fortran `dcon.in` + `equil.in` +
`pentrc.in` from the kinetic example, plus a symlink (or copy) to the
EFIT g-file. The `[KineticForces]` section points at the Fortran `.kin`
file by absolute path.
"""
function build_benchmark_tomldir(eq_file::String, kin_file::String)
    tmpdir = mktempdir(; prefix="diiid_kinetic_dcon_bench_")
    eq_name = basename(eq_file)
    try
        symlink(eq_file, joinpath(tmpdir, eq_name))
    catch
        cp(eq_file, joinpath(tmpdir, eq_name))
    end
    open(joinpath(tmpdir, "gpec.toml"), "w") do io
        println(
            io,
            """
# Auto-generated by benchmark_diiid_kinetic_stability.jl — do not edit.

[Equilibrium]
eq_filename = "$eq_name"
eq_type = "efit"
jac_type = "hamada"
power_bp = 0
power_b = 0
power_r = 0
grid_type = "pow1"             # Matches Fortran DIIID_kinetic_example (equil/grid.f90 powspace)
psilow = 0.01
psihigh = 0.993
mpsi = 128
mtheta = 256
newq0 = 0
etol = 1e-7

[Wall]
shape = "nowall"

[ForceFreeStates]
bal_flag = false
mat_flag = true
ode_flag = true
vac_flag = true
mer_flag = true
force_termination = true       # Skip PE+KF post-processing — we only need FFS eigenvalues

psiedge = 1.0                 # No edge-scan truncation (dmlim mechanism removed in develop)
qlow = 1.02
qhigh = 1e3
sing_start = 0

nn_low = 1
nn_high = 1
delta_mlow = 8
delta_mhigh = 8
mthvac = 512
thmax0 = 1

kinetic_source = "calculated"
kinetic_factor = 1.0
eulerlagrange_tolerance = 1e-7
singfac_min = 1e-4
ucrit = 1e4
write_outputs_to_HDF5 = true

[KineticForces]
kinetic_file = "$kin_file"
nn = 1
nl = 4
zi = 1
mi = 2
nutype = "harmonic"
f0type = "maxwellian"
"""
        )
    end
    return tmpdir
end

_p(args...) = (println(stderr, args...); flush(stderr))
_pf(fmt, args...) = (print(stderr, Printf.format(Printf.Format(fmt), args...)); flush(stderr))

function run_benchmark(fortran_dir::String=DEFAULT_FORTRAN_DIR)
    _p("=" ^ 70)
    _p("  DIIID Kinetic-DCON Benchmark: Julia KF→FFS vs Fortran DCON")
    _p("  Fortran example: $fortran_dir")
    _p("=" ^ 70)

    inputs = discover_inputs(fortran_dir)
    ref = read_dcon_reference(inputs.dcon_nc)
    _pf("  EFIT g-file: %s\n", basename(inputs.eq_file))
    _pf("  Kinetic:     %s\n", basename(inputs.kin_file))
    _pf("  Reference (W_t_eigenvalue[1]): Re = %.6f  Im = %.6f\n",
        ref.W_t_re, ref.W_t_im)

    tomldir = build_benchmark_tomldir(inputs.eq_file, inputs.kin_file)

    _p("\n--- Running GPE.main with kinetic_source=\"calculated\" ---")
    t0 = time()
    GPE.main([tomldir])
    wall = time() - t0
    _pf("  GPE.main completed in %.1f s\n", wall)

    # Read Julia result
    h5path = joinpath(tomldir, "gpec.h5")
    isfile(h5path) || error("Expected Julia output not found: $h5path")

    et = h5open(h5path, "r") do h5
        read(h5["vacuum/et"])
    end
    isempty(et) && error("vacuum/et is empty in $h5path")
    # et is stored as a length-2*N real array (re,im interleaved) by HDF5.jl
    # when the underlying Julia array is ComplexF64. NCDatasets and HDF5 give
    # us a ComplexF64 array directly here.
    julia_re = real(et[1])
    julia_im = imag(et[1])

    re_err = abs(julia_re - ref.W_t_re) / abs(ref.W_t_re) * 100
    im_err = abs(julia_im - ref.W_t_im) / abs(ref.W_t_im) * 100

    _p("\n" * "=" ^ 70)
    _p("  Results Comparison (kinetic-DCON least-stable eigenvalue)")
    _p("=" ^ 70)
    _pf("  Re(et[1]):  Julia = %12.6f  Fortran = %12.6f  err = %6.2f%%\n",
        julia_re, ref.W_t_re, re_err)
    _pf("  Im(et[1]):  Julia = %12.6f  Fortran = %12.6f  err = %6.2f%%\n",
        julia_im, ref.W_t_im, im_err)
    _p("\n  Plasma/vacuum partition (Fortran least-stable, separate diag.):")
    _pf("    W_p[1] = %.6f + %.6fi\n", ref.W_p_re, ref.W_p_im)
    _pf("    W_v[1] = %.6f + %.6fi\n", ref.W_v_re, ref.W_v_im)

    # Acceptance check
    re_pass = re_err <= 5.0
    im_pass = im_err <= 20.0
    im_stretch = im_err <= 5.0

    _p("\n" * "=" ^ 70)
    if re_pass && im_pass
        _p("  PASS — Re within 5 %, Im within 20 %" *
           (im_stretch ? " (stretch: Im within 5 %)" : ""))
    else
        _p("  FAIL — thresholds exceeded:")
        re_pass || _pf("    Re err %.2f%% > 5%%\n", re_err)
        im_pass || _pf("    Im err %.2f%% > 20%%\n", im_err)
    end
    _p("=" ^ 70)

    # cond(F̄) vs ψ diagnostic — shows whether kinetic singular surfaces
    # (det(F̄)=0) were found and why peaks were/weren't accepted.
    png_path = joinpath(@__DIR__, "diiid_kinetic_cond_fbar.png")
    if AnalysisFFS.plot_cond_fbar(h5path; save_path=png_path) !== nothing
        println("  cond(F̄) plot: ", abspath(png_path))
    end

    return (; julia_re, julia_im,
        fortran_re=ref.W_t_re, fortran_im=ref.W_t_im,
        re_err, im_err, wall, tomldir)
end

# Run only when invoked as a script.
if abspath(PROGRAM_FILE) == @__FILE__
    fortran_dir = length(ARGS) >= 1 ? ARGS[1] :
                  get(ENV, "GPEC_FORTRAN_DIIID_DCON", DEFAULT_FORTRAN_DIR)
    run_benchmark(fortran_dir)
end
