#!/usr/bin/env julia
"""
    benchmark_diiid_ideal_ntv_torque.jl

Benchmark Julia KineticForces NTV against Fortran PENTRC reference values.

Operates on a Fortran GPEC example directory — uses its equilibrium file (g*),
kinetic file (g*.kin), and Fortran output files (`gpec_xclebsch_n1.out`,
`pentrc_output_n1.nc`). No inputs are duplicated into this repo. A minimal
Julia `gpec.toml` with benchmark-appropriate settings is built in a temp
directory at runtime.

Loads Fortran `gpec_xclebsch_n1.out` to populate PE Clebsch fields directly,
then runs the KF JBB deweighting + torque integration pipeline — this
isolates KF from the PE pipeline for direct comparison.

Reference values are read from `pentrc_output_n1.nc` global attributes in
the Fortran example directory.

Usage:
    julia --project=. benchmarks/benchmark_diiid_ideal_ntv_torque.jl [fortran_dir]

    fortran_dir defaults to \$GPEC_FORTRAN_DIIID or
    ~/Code/gpec/docs/examples/DIIID_ideal_example.
"""

using Printf
using NCDatasets
using Plots

# Load GPEC
using GeneralizedPerturbedEquilibrium
const GPE = GeneralizedPerturbedEquilibrium
const FFS = GPE.ForceFreeStates
const KF = GPE.KineticForces
const Eq = GPE.Equilibrium
const PE = GPE.PerturbedEquilibrium

const DEFAULT_FORTRAN_DIR = expanduser("~/Code/gpec/docs/examples/DIIID_ideal_example")

"""
    discover_inputs(fortran_dir) → (; eq_file, kin_file, xclebsch, pentrc_nc)

Locate the EFIT g-file, `.kin` kinetic profile, and reference output files
inside a Fortran GPEC example directory. Errors if any required file is
missing or if the g-file cannot be uniquely identified.
"""
function discover_inputs(fortran_dir::String)
    isdir(fortran_dir) || error("Fortran example directory not found: $fortran_dir")
    # EFIT g-files start with "g" followed by a digit; exclude .kin, backups,
    # and gpec_* output files.
    eq_candidates = filter(readdir(fortran_dir)) do f
        length(f) >= 2 && f[1] == 'g' && isdigit(f[2]) &&
            !endswith(f, ".kin") && !endswith(f, ".bak") &&
            !startswith(f, "gpec_")
    end
    length(eq_candidates) == 1 ||
        error("Expected exactly one EFIT g-file in $fortran_dir; found: $eq_candidates")
    eq_file = joinpath(fortran_dir, eq_candidates[1])
    kin_file = eq_file * ".kin"
    xclebsch = joinpath(fortran_dir, "gpec_xclebsch_n1.out")
    pentrc_nc = joinpath(fortran_dir, "pentrc_output_n1.nc")
    for (label, path) in [("kinetic profile", kin_file),
        ("xclebsch output", xclebsch),
        ("pentrc NetCDF", pentrc_nc)]
        isfile(path) || error("$label not found: $path")
    end
    return (; eq_file, kin_file, xclebsch, pentrc_nc)
end

"""
    read_pentrc_reference(pentrc_nc) → NamedTuple

Read `T_total_*` and `dW_total_*` scalar reference values from the Fortran
`pentrc_output_n1.nc` global attributes.
"""
function read_pentrc_reference(pentrc_nc::String)
    NCDatasets.Dataset(pentrc_nc, "r") do ds
        gatt = ds.attrib
        return (
            T_total_fgar=Float64(gatt["T_total_fgar"]),
            T_total_tgar=Float64(gatt["T_total_tgar"]),
            dW_total_fgar=Float64(gatt["dW_total_fgar"]),
            dW_total_tgar=Float64(gatt["dW_total_tgar"])
        )
    end
end

"""
    build_benchmark_tomldir(eq_file) → tmpdir

Construct a temporary directory containing a Julia `gpec.toml` with the
benchmark's fixed Julia-side settings (grid, tolerances, jac_type, etc.) and
a symlink (or copy) to the Fortran EFIT g-file. Returns the tmpdir path so
`GPE.main([tmpdir])` can run against it.
"""
function build_benchmark_tomldir(eq_file::String)
    tmpdir = mktempdir(; prefix="diiid_kinetic_bench_")
    eq_name = basename(eq_file)
    # Symlink is cheap and keeps the dir small. Fall back to copy if the OS
    # disallows symlinks (rare on darwin/linux).
    try
        symlink(eq_file, joinpath(tmpdir, eq_name))
    catch
        cp(eq_file, joinpath(tmpdir, eq_name))
    end
    open(joinpath(tmpdir, "gpec.toml"), "w") do io
        println(
            io,
            """
# Auto-generated by benchmark_diiid_ideal_ntv_torque.jl — do not edit.

[Equilibrium]
eq_filename = "$eq_name"
eq_type = "efit"
jac_type = "hamada"
power_bp = 0
power_b = 0
power_r = 0
grid_type = "ldp"
psilow = 1e-4
psihigh = 0.993
mpsi = 128
mtheta = 256
newq0 = 0
etol = 1e-7

[Wall]
shape = "nowall"

[ForceFreeStates]
bal_flag = false
mat_flag = true
ode_flag = true
vac_flag = true
mer_flag = true
force_termination = false

psiedge = 1.00                # No edge-scan truncation (dmlim mechanism removed in develop)
qlow = 1.02
qhigh = 1e3
sing_start = 0

nn_low = 1
nn_high = 1
delta_mlow = 8
delta_mhigh = 8
mthvac = 512
thmax0 = 1

kinetic_source = "fixed"
kinetic_factor = 0.0
eulerlagrange_tolerance = 1e-7
save_interval = 3
singfac_min = 1e-4
ucrit = 1e4
"""
        )
    end
    return tmpdir
end

"""
    load_fortran_xclebsch(filepath) → (psi_grid, clebsch_psi, clebsch_psi1, clebsch_alpha, mpert, mlow)

Parse Fortran `gpec_xclebsch_n1.out` into arrays matching PE xi_modes layout.

Header format:
Line 1: title
Line 6: mstep, mpert, mthsurf
Line 8: column headers
Line 9+: data (psi, m, 6 floats)
"""
function load_fortran_xclebsch(filepath::String)
    lines = readlines(filepath)

    # Parse mpert from header line 6: "      mstep =   1537      mpert =  34   mthsurf = 512"
    header_line = lines[6]
    m_mpert = match(r"mpert\s*=\s*(\d+)", header_line)
    mpert = parse(Int, m_mpert[1])

    # Find first data line (skip headers)
    data_start = 9
    data_lines = lines[data_start:end]
    filter!(l -> !isempty(strip(l)), data_lines)

    # Determine mlow from first data block
    first_m = parse(Int, split(data_lines[1])[2])
    mlow = first_m

    # Parse data
    ndata = length(data_lines)
    npsi_total = ndata ÷ mpert
    @assert ndata == npsi_total * mpert "Data count $ndata not divisible by mpert=$mpert"

    psi_vals = Float64[]
    clebsch_psi1_data = zeros(ComplexF64, npsi_total, mpert)
    clebsch_psi_data = zeros(ComplexF64, npsi_total, mpert)
    clebsch_alpha_data = zeros(ComplexF64, npsi_total, mpert)

    idx = 0
    for i in 1:npsi_total
        for j in 1:mpert
            idx += 1
            vals = parse.(Float64, split(data_lines[idx]))
            psi = vals[1]
            m = Int(vals[2])
            if j == 1
                push!(psi_vals, psi)
            end
            ipert = m - mlow + 1
            @assert 1 <= ipert <= mpert "Mode m=$m out of range [mlow=$mlow, mhigh=$(mlow+mpert-1)]"
            clebsch_psi1_data[i, ipert] = complex(vals[3], vals[4])   # ∂ξ^ψ/∂ψ
            clebsch_psi_data[i, ipert] = complex(vals[5], vals[6])   # ξ^ψ
            clebsch_alpha_data[i, ipert] = complex(vals[7], vals[8])   # ξ^α
        end
    end

    return psi_vals, clebsch_psi_data, clebsch_psi1_data, clebsch_alpha_data, mpert, mlow
end


_p(args...) = (println(stderr, args...); flush(stderr))
_pf(fmt, args...) = (print(stderr, Printf.format(Printf.Format(fmt), args...)); flush(stderr))

function run_benchmark(fortran_dir::String=DEFAULT_FORTRAN_DIR)
    _p("=" ^ 70)
    _p("  DIIID Kinetic Benchmark: Julia KineticForces vs Fortran PENTRC")
    _p("  Fortran example: $fortran_dir")
    _p("=" ^ 70)

    inputs = discover_inputs(fortran_dir)
    ref = read_pentrc_reference(inputs.pentrc_nc)
    _pf("  EFIT g-file: %s\n", basename(inputs.eq_file))
    _pf("  Kinetic:     %s\n", basename(inputs.kin_file))

    tomldir = build_benchmark_tomldir(inputs.eq_file)

    # Run FFS via main() on the tmpdir
    _p("\n--- Equilibrium + ForceFreeStates (via main()) ---")
    t0 = time()
    result = GPE.main([tomldir])
    equil = result.equil
    intr = result.intr
    ctrl = result.ctrl

    _pf("  FFS completed in %.1f s\n", time() - t0)
    _pf("  mpert=%d, mlow=%d, mhigh=%d\n", intr.mpert, intr.mlow, intr.mhigh)

    # Build metric (needed for JBB deweighting)
    metric = FFS.make_metric(equil, intr.mpert)

    # Load Fortran xclebsch data
    _p("\n--- Load Fortran xclebsch ---")
    psi_grid_f, clebsch_psi, clebsch_psi1, clebsch_alpha, mpert_f, mlow_f =
        load_fortran_xclebsch(inputs.xclebsch)

    npsi_f = length(psi_grid_f)
    _pf("  Loaded %d ψ surfaces, mpert=%d, mlow=%d from Fortran xclebsch\n",
        npsi_f, mpert_f, mlow_f)
    _pf("  ψ range: [%.6f, %.6f]\n", psi_grid_f[1], psi_grid_f[end])

    if mpert_f != intr.mpert || mlow_f != intr.mlow
        @warn "Mode ranges differ: Fortran mpert=$mpert_f,mlow=$mlow_f vs Julia mpert=$(intr.mpert),mlow=$(intr.mlow)"
    end

    # Build PE state from Fortran data and run JBB deweighting
    _p("\n--- Build PE state (Fortran Clebsch → dbob_m/divx_m) ---")
    t1 = time()

    # Construct PerturbedEquilibriumState with Fortran Clebsch data
    # Fortran xclebsch stores ξ^α directly; PE convention is ξ^α/χ₁
    chi1 = 2π * equil.psio
    pe_state = PE.PerturbedEquilibriumState(;
        psi_grid=psi_grid_f,
        xi_modes=(
            clebsch_psi=clebsch_psi,
            clebsch_psi1=clebsch_psi1,
            clebsch_alpha=clebsch_alpha ./ chi1  # Store as ξ^α/χ₁ per PE convention
        )
    )

    # KF configuration matching Fortran pentrc.in.
    # tgar defaults off during perf iteration (same kernels as fgar; see
    # memory/feedback_kf_fgar_subsumes_tgar.md). Set BENCHMARK_TGAR=1 to enable
    # for the final full-validation run.
    tgar_enabled = get(ENV, "BENCHMARK_TGAR", "0") == "1"
    kf_ctrl = KF.KineticForcesControl(;
        fgar_flag=true, tgar_flag=tgar_enabled, nn=1, nl=4,
        mi=2, zi=1, nutype="harmonic", f0type="maxwellian",
        nufac=1, psilims=[0.0, 1.0], kinetic_file=inputs.kin_file,
        verbose=false)

    # Initialize KF internal state
    kf_intr = KF.KineticForcesInternal(equil; verbose=false)

    # Run set_perturbation_data! — builds dbob_m, divx_m, xs_m via JBB deweighting
    KF.set_perturbation_data!(kf_intr, pe_state, intr, equil, metric)

    _pf("  JBB deweighting completed in %.1f s\n", time() - t1)

    # Sanity checks
    if kf_intr.dbob_m === nothing || kf_intr.divx_m === nothing
        error("dbob_m or divx_m is nothing after set_perturbation_data!")
    end

    # Sample dbob_m at midplane
    psi_mid = 0.5
    dbob_sample = kf_intr.dbob_m(psi_mid)
    divx_sample = kf_intr.divx_m(psi_mid)
    _pf("  dbob_m(ψ=0.5) max|mode| = %.4e\n", maximum(abs.(dbob_sample)))
    _pf("  divx_m(ψ=0.5) max|mode| = %.4e\n", maximum(abs.(divx_sample)))

    # Load kinetic profiles and run torque integration
    _p("\n--- Torque integration ---")
    t2 = time()

    kinetic_profiles = Eq.load_kinetic_profiles(
        kf_ctrl.kinetic_file;
        zi=kf_ctrl.zi, zimp=kf_ctrl.zimp, mi=kf_ctrl.mi, mimp=kf_ctrl.mimp)

    kf_state = KF.KineticForcesState()
    KF.compute_torque_all_methods!(kf_state, kf_intr, kf_ctrl, equil, kinetic_profiles)

    kf_runtime = time() - t2
    _pf("  Torque integration completed in %.1f s\n", kf_runtime)

    # ψ-step count per method — a key KPI for outer-ODE tolerance tuning.
    _p("\n  ψ-step counts (outer Tsit5 accepted steps per method):")
    for (method_key, mr) in kf_state.method_results
        _pf("    %-5s: %5d accepted ψ-steps\n", method_key, mr.psi_nsteps)
    end

    # Compare results
    _p("\n" * "=" ^ 70)
    _p("  Results Comparison")
    _p("=" ^ 70)

    results = Dict{String,NamedTuple}()

    for (method_key, ref_T, ref_dW) in [
        ("fgar", ref.T_total_fgar, ref.dW_total_fgar),
        ("tgar", ref.T_total_tgar, ref.dW_total_tgar)]

        if haskey(kf_state.method_results, method_key)
            mr = kf_state.method_results[method_key]
            T_julia = real(mr.total_torque)
            dW_julia = real(mr.total_energy)
            T_err = abs(T_julia - ref_T) / abs(ref_T) * 100
            dW_err = abs(dW_julia - ref_dW) / abs(ref_dW) * 100

            results[method_key] = (; T_julia, dW_julia, T_err, dW_err)

            _pf("\n  %-5s Torque:  Julia = %12.6f  Fortran = %12.6f  err = %6.2f%%\n",
                uppercase(method_key), T_julia, ref_T, T_err)
            _pf("  %-5s Energy:  Julia = %12.6f  Fortran = %12.6f  err = %6.2f%%\n",
                uppercase(method_key), dW_julia, ref_dW, dW_err)
        else
            _pf("\n  %-5s: NOT RUN\n", uppercase(method_key))
        end
    end

    _p("\n" * "=" ^ 70)

    # Check pass/fail
    all_pass = true
    for (method_key, r) in results
        if r.T_err > 5.0 || r.dW_err > 5.0
            @warn "$(uppercase(method_key)) exceeds 5% threshold" T_err=r.T_err dW_err=r.dW_err
            all_pass = false
        end
    end

    if all_pass && !isempty(results)
        _p("  All methods within 5% of Fortran reference")
    elseif isempty(results)
        _p("  No methods produced results")
    else
        _p("  Some methods exceed 5% threshold")
    end

    # Plot dT/dψ and T(ψ) overlay vs Fortran PENTRC reference
    _p("\n" * "=" ^ 70)
    _p("  Plotting dT/dψ and T(ψ) overlay vs Fortran")
    _p("=" ^ 70)

    pentrc_nc = inputs.pentrc_nc

    # Read Fortran reference profiles. PENTRC writes NetCDF in Fortran order
    # `dTdpsi_<method>(i, ell, psi)` with i∈{1,2}={real,imag}; NCDatasets
    # preserves that order in the Julia array, so we slice [1, :, :] for real
    # and sum over ell (dim 1 of the resulting 2D array).
    fortran_profiles = Dict{String,NamedTuple}()
    NCDatasets.Dataset(pentrc_nc, "r") do ds
        for method_key in keys(results)
            psi_var = "psi_$method_key"
            dt_var = "dTdpsi_$method_key"
            T_var = "T_$method_key"
            if !(haskey(ds, psi_var) && haskey(ds, dt_var) && haskey(ds, T_var))
                @warn "Fortran NetCDF missing variables for method" method=method_key
                continue
            end
            psi_f = Array(ds[psi_var][:])
            dTdpsi_f = Array(ds[dt_var][:, :, :])    # (i, ell, psi)
            T_f = Array(ds[T_var][:, :, :])
            # Take real slice (i=1), sum over ell (dim 1 of the 2D real slice → (psi,))
            dT_re_f = dropdims(sum(dTdpsi_f[1, :, :]; dims=1); dims=1)
            T_re_f = dropdims(sum(T_f[1, :, :]; dims=1); dims=1)
            fortran_profiles[method_key] = (; psi=psi_f, dTdpsi=dT_re_f, T=T_re_f)
            _pf("  Fortran %-5s: %d ψ points, T_final = %.6f N·m\n",
                method_key, length(psi_f), T_re_f[end])
        end
    end

    # Plot per method: two panels (dT/dψ, cumulative T) saved as separate PNGs.
    # Separate files avoid a GR-backend rendering bug that surfaced when
    # stacking panels into a layout=(2,N) figure with Float64 arrays of
    # different lengths. Simpler is also easier to regenerate outside the full
    # benchmark: the raw arrays are dumped to `.dat` so a standalone plot
    # script can re-draw without a 5-minute rerun.
    method_keys = sort(collect(intersect(keys(results), keys(fortran_profiles))))
    if isempty(method_keys)
        @warn "No overlapping methods between Julia and Fortran; skipping plot"
        return results
    end

    for mkey in method_keys
        mr = kf_state.method_results[mkey]
        fp = fortran_profiles[mkey]

        _pf("  %s: Julia psi_grid=%d, dtdpsi=%d, t_cum=%d | Fortran psi=%d, dTdpsi=%d, T=%d\n",
            mkey, length(mr.psi_grid), length(mr.dtdpsi), length(mr.t_cumulative),
            length(fp.psi), length(fp.dTdpsi), length(fp.T))

        # Dump raw arrays so the plot can be regenerated without rerunning.
        open(joinpath(@__DIR__, "kf_$(mkey)_profiles.dat"), "w") do io
            println(io, "# psi_julia  dTdpsi_julia_re  T_julia_re")
            for i in eachindex(mr.psi_grid)
                @printf(io, "%.8e  %.8e  %.8e\n",
                    mr.psi_grid[i], real(mr.dtdpsi[i]), real(mr.t_cumulative[i]))
            end
            println(io, "# --- fortran ---")
            println(io, "# psi_fortran  dTdpsi_fortran  T_fortran")
            for i in eachindex(fp.psi)
                @printf(io, "%.8e  %.8e  %.8e\n", fp.psi[i], fp.dTdpsi[i], fp.T[i])
            end
        end

        # dT/dψ panel
        p1 = plot(; xlabel="ψ_n", ylabel="dT/dψ [N·m]",
            title="$(uppercase(mkey)): dT/dψ", legend=:topleft,
            left_margin=12Plots.mm, bottom_margin=4Plots.mm, size=(900, 500))
        plot!(p1, Float64.(fp.psi), Float64.(fp.dTdpsi);
            label="Fortran", lw=2, color=:black, linestyle=:dash)
        plot!(p1, Float64.(mr.psi_grid), Float64.(real.(mr.dtdpsi));
            label="Julia", lw=1.5, color=:crimson)
        path1 = joinpath(@__DIR__, "kf_$(mkey)_dTdpsi_vs_fortran.png")
        try
            savefig(p1, path1)
            _p("  Saved dT/dψ panel → $path1")
        catch err
            @warn "dT/dψ panel savefig failed" method=mkey err
        end

        # Cumulative T panel
        p2 = plot(; xlabel="ψ_n", ylabel="T [N·m]",
            title="$(uppercase(mkey)): cumulative T", legend=:topleft,
            left_margin=12Plots.mm, bottom_margin=4Plots.mm, size=(900, 500))
        plot!(p2, Float64.(fp.psi), Float64.(fp.T);
            label="Fortran", lw=2, color=:black, linestyle=:dash)
        plot!(p2, Float64.(mr.psi_grid), Float64.(real.(mr.t_cumulative));
            label="Julia", lw=1.5, color=:crimson)
        path2 = joinpath(@__DIR__, "kf_$(mkey)_T_vs_fortran.png")
        try
            savefig(p2, path2)
            _p("  Saved cumulative T panel → $path2")
        catch err
            @warn "cumulative T panel savefig failed" method=mkey err
        end
    end

    return results
end

# Run only when invoked as a script (so other benchmarks can `include()` this
# file to reuse `load_fortran_xclebsch` without triggering the full run).
if abspath(PROGRAM_FILE) == @__FILE__
    fortran_dir = length(ARGS) >= 1 ? ARGS[1] : get(ENV, "GPEC_FORTRAN_DIIID", DEFAULT_FORTRAN_DIR)
    results = run_benchmark(fortran_dir)
end
