#!/usr/bin/env julia
"""
    dump_julia_kinetic_matrices.jl

Dump the six kinetic matrices (Ak, Bk, Ck, Dk, Ek, Hk per Logan 2015
thesis Eqs 7.30–7.35) at three ψ surfaces (0.1, 0.5, 0.9) for n=1,
ℓ=0 only, from the Julia KineticForces per-surface entry point
`compute_kinetic_matrices_at_psi!`.

Only ℓ=0 is dumped because the Fortran reference (pentrc.F90:115 wxyz
block) writes only ℓ=0 and will not be extended soon. Comparing ℓ=0
matrices is sufficient for the Phase-B bug hunt.

Output: `benchmarks/julia_kinetic_matrices_n1.h5` with HDF5 groups
    psi=<v>/{Ak, Bk, Ck, Dk, Ek, Hk}
each dataset ComplexF64[mpert, mpert]. Metadata (`mfac`, `nn`,
per-surface and total wall times) stored as attributes.

This is the Julia half of the per-surface matrix-validation diagnostic
from the "Per-surface kinetic matrix debugging" plan. The Fortran half
is generated by the companion script `compare_kinetic_matrices.jl`,
which runs Fortran pentrc with `wxyz_flag=.true.` + `psi_out=0.1,0.5,0.9`
and parses the resulting `pentrc_tgar_elmat_n1.out`.

The script reuses the Fortran-example discovery helper from
`benchmark_diiid_kinetic_dcon.jl` and writes a stripped-down `gpec.toml`
with `nl=1, nn=1` for fast per-surface iteration.

Usage:
    julia --project=. benchmarks/dump_julia_kinetic_matrices.jl [fortran_dir] [out_h5] [pitch_integrator]

`pitch_integrator` ∈ {"ode", "quadgk"} selects the pitch-angle quadrature
used inside `calculate_gar_matrices!`. Default is "ode" (coupled Tsit5);
"quadgk" exercises the vector-valued adaptive Gauss-Kronrod path added in
Phase C2.
"""

using Printf
using HDF5
using TOML
using FastInterpolations

using GeneralizedPerturbedEquilibrium
const GPE = GeneralizedPerturbedEquilibrium

using .GPE.Equilibrium: EquilibriumConfig, setup_equilibrium, load_kinetic_profiles
using .GPE.ForceFreeStates: ForceFreeStatesInternal, ForceFreeStatesControl
using .GPE.ForceFreeStates: sing_lim!, sing_find!, mercier_scan!, make_metric, make_matrix
using .GPE.ForceFreeStates: build_kinetic_metric_matrices
using .GPE.KineticForces: KineticForcesInternal, KineticForcesControl,
    compute_kinetic_matrices_at_psi!

const DEFAULT_FORTRAN_DIR =
    expanduser("~/Code/gpec/docs/examples/DIIID_kinetic_example")
const DEFAULT_OUT_H5 =
    joinpath(@__DIR__, "julia_kinetic_matrices_n1.h5")

const PSI_SURFACES = (0.1, 0.5, 0.9)
const ELL = 0   # Fortran wxyz dumps only ℓ=0; match for comparison
const NN = 1

"""
    discover_inputs(fortran_dir) → (; eq_file, kin_file)

Same helper signature as `benchmark_diiid_kinetic_dcon.jl` but only
needs the EFIT g-file and its `.kin` sibling.
"""
function discover_inputs(fortran_dir::String)
    isdir(fortran_dir) || error("Fortran example directory not found: $fortran_dir")
    eq_candidates = filter(readdir(fortran_dir)) do f
        length(f) >= 2 && f[1] == 'g' && isdigit(f[2]) &&
            !endswith(f, ".kin") && !endswith(f, ".bak") &&
            !startswith(f, "gpec_")
    end
    length(eq_candidates) == 1 ||
        error("Expected exactly one EFIT g-file in $fortran_dir; found: $eq_candidates")
    eq_file = joinpath(fortran_dir, eq_candidates[1])
    kin_file = eq_file * ".kin"
    isfile(kin_file) || error("kinetic profile not found: $kin_file")
    return (; eq_file, kin_file)
end

"""
    build_tomldir(eq_file, kin_file) → tmpdir

Temporary `gpec.toml` directory matching the Fortran `pentrc.in` +
`equil.in` + `dcon.in` from the DIIID kinetic example, with
`nn=1, nl=1` to keep per-surface wall time small.
"""
function build_tomldir(eq_file::String, kin_file::String)
    tmpdir = mktempdir(; prefix="julia_fkmm_dump_")
    eq_name = basename(eq_file)
    try
        symlink(eq_file, joinpath(tmpdir, eq_name))
    catch
        cp(eq_file, joinpath(tmpdir, eq_name))
    end
    open(joinpath(tmpdir, "gpec.toml"), "w") do io
        println(io, """
        # Auto-generated by dump_julia_kinetic_matrices.jl — do not edit.
        [Equilibrium]
        eq_filename = "$eq_name"
        eq_type = "efit"
        jac_type = "hamada"
        power_bp = 0
        power_b = 0
        power_r = 0
        grid_type = "ldp"
        psilow = 0.01
        psihigh = 0.993
        mpsi = 128
        mtheta = 256
        newq0 = 0
        etol = 1e-7

        [Wall]
        shape = "nowall"

        [ForceFreeStates]
        bal_flag = false
        mat_flag = true
        ode_flag = false
        vac_flag = false
        mer_flag = true
        force_termination = true

        set_psilim_via_dmlim = true
        dmlim = 0.2
        psiedge = 1.0
        qlow = 1.02
        qhigh = 1e3
        sing_start = 0

        nn_low = $NN
        nn_high = $NN
        delta_mlow = 8
        delta_mhigh = 8
        delta_mband = 0
        mthvac = 512
        thmax0 = 1

        kinetic_source = "calculated"
        kinetic_factor = 1.0
        eulerlagrange_tolerance = 1e-7

        [KineticForces]
        kinetic_file = "$kin_file"
        nn = $NN
        nl = 1
        zi = 1
        mi = 2
        nutype = "harmonic"
        f0type = "maxwellian"
        """)
    end
    return tmpdir
end

"""
    setup_internals(tomldir) → (; equil, ffs_intr, kf_intr, kf_ctrl, kinetic_profiles, mpert, mfac)

Replicates the early part of `GPE.main` up through building the metric,
FourFitVars, and the kinetic geometric matrices — but does not call the
Euler–Lagrange ODE or any other post-setup work. The returned
`kf_intr` is populated with mode indexing and `smats/tmats/xmats/ymats/zmats`
but no perturbation data (`dbob_m`, `divx_m`) — the matrix kernel gates
on `isnothing(intr.dbob_m)` and feeds zeros in that case (Torque.jl:70-77).
"""
function setup_internals(tomldir::String)
    inputs = TOML.parsefile(joinpath(tomldir, "gpec.toml"))
    ctrl = ForceFreeStatesControl(;
        (Symbol(k) => v for (k, v) in inputs["ForceFreeStates"])...)
    intr = ForceFreeStatesInternal(; dir_path=tomldir)

    # Equilibrium
    eq_config = EquilibriumConfig(inputs["Equilibrium"], intr.dir_path)
    equil = setup_equilibrium(eq_config)

    # Wall (kept for completeness even though vac_flag=false)
    if "Wall" in keys(inputs)
        intr.wall_settings = GPE.Vacuum.WallShapeSettings(;
            (Symbol(k) => v for (k, v) in inputs["Wall"])...)
    else
        intr.wall_settings = GPE.Vacuum.WallShapeSettings()
    end

    # Match main()'s delta_mhigh doubling convention
    ctrl.delta_mhigh *= 2

    sing_lim!(intr, ctrl, equil)

    # Mercier (required so intr.locstab is populated — sing_find uses it indirectly)
    profiles_xs = equil.profiles.xs
    locstab_fs = zeros(Float64, length(profiles_xs), 5)
    mercier_scan!(locstab_fs, equil)
    intr.locstab = cubic_interp(profiles_xs, Series(locstab_fs);
        extrap=ExtendExtrap())

    # Mode numbers
    intr.nlow = ctrl.nn_low
    intr.nhigh = ctrl.nn_high
    intr.npert = intr.nhigh - intr.nlow + 1

    sing_find!(intr, equil)

    intr.mlow = trunc(Int, min(intr.nlow * equil.params.qmin, 0)) - 4 - ctrl.delta_mlow
    intr.mhigh = trunc(Int, intr.nhigh * equil.params.qmax) + ctrl.delta_mhigh
    intr.mpert = intr.mhigh - intr.mlow + 1
    intr.mband = intr.mpert - 1 - ctrl.delta_mband
    intr.mband = min(max(intr.mband, 0), intr.mpert - 1)
    intr.numpert_total = intr.mpert * intr.npert

    kf_ctrl = KineticForcesControl(;
        (Symbol(k) => v for (k, v) in inputs["KineticForces"])...)
    kinetic_file = joinpath(intr.dir_path, kf_ctrl.kinetic_file)
    kinetic_profiles = load_kinetic_profiles(kinetic_file;
        zi=kf_ctrl.zi, zimp=kf_ctrl.zimp,
        mi=kf_ctrl.mi, mimp=kf_ctrl.mimp)

    metric = make_metric(equil; mband=intr.mband, fft_flag=ctrl.fft_flag)
    ffit = make_matrix(equil, intr, metric)
    @assert ffit.numpert_total == intr.numpert_total "FourFitVars / FFSInternal numpert mismatch"

    # Build KineticForcesInternal with geometric matrices wired in (mirrors
    # CalculatedKineticMatrices.jl:72-88). Leaves dbob_m/divx_m unset; the
    # matrix kernel tolerates that and zeros them internally.
    kf_intr = KineticForcesInternal(equil; verbose=false)
    kf_intr.mlow = intr.mlow
    kf_intr.mhigh = intr.mhigh
    kf_intr.mpert = intr.mpert
    kf_intr.nlow = intr.nlow
    kf_intr.nhigh = intr.nhigh
    kf_intr.npert = intr.npert
    kf_intr.numpert_total = intr.numpert_total
    kf_intr.mfac = collect(intr.mlow:intr.mhigh)

    geom_mats = build_kinetic_metric_matrices(equil, intr, metric)
    kf_intr.smats = geom_mats.smats
    kf_intr.tmats = geom_mats.tmats
    kf_intr.xmats = geom_mats.xmats
    kf_intr.ymats = geom_mats.ymats
    kf_intr.zmats = geom_mats.zmats

    return (; equil, ffs_intr=intr, kf_intr, kf_ctrl, kinetic_profiles,
              mpert=intr.mpert, mfac=kf_intr.mfac)
end

"""
    dump_matrices(fortran_dir, out_h5)

End-to-end dump driver. Returns a NamedTuple with the wall-time summary
so a calling script (A3) can print a unified runtime comparison.
"""
function dump_matrices(fortran_dir::String=DEFAULT_FORTRAN_DIR,
                       out_h5::String=DEFAULT_OUT_H5;
                       pitch_integrator::Symbol=:ode)
    pitch_integrator in (:ode, :quadgk) ||
        error("pitch_integrator must be :ode or :quadgk, got :$pitch_integrator")
    println(stderr, "=" ^ 70)
    println(stderr, "  Julia per-surface kinetic matrix dumper")
    println(stderr, "  Fortran example:   $fortran_dir")
    println(stderr, "  Output:            $out_h5")
    println(stderr, "  pitch_integrator:  :$pitch_integrator")
    println(stderr, "=" ^ 70)

    inputs = discover_inputs(fortran_dir)
    tomldir = build_tomldir(inputs.eq_file, inputs.kin_file)

    t_setup0 = time()
    state = setup_internals(tomldir)
    t_setup = time() - t_setup0
    @printf(stderr, "  setup time:      %6.2f s  (mpert=%d)\n", t_setup, state.mpert)

    # Output buffers
    mpert = state.mpert
    per_surface_wall = Dict{Float64,Float64}()

    # HDF5 write
    total_t0 = time()
    h5open(out_h5, "w") do h5
        attributes(h5)["nn"] = NN
        attributes(h5)["ell"] = ELL
        attributes(h5)["mpert"] = mpert
        attributes(h5)["mlow"] = state.ffs_intr.mlow
        attributes(h5)["mhigh"] = state.ffs_intr.mhigh
        attributes(h5)["pitch_integrator"] = String(pitch_integrator)
        write(h5, "mfac", state.mfac)

        block_w = zeros(ComplexF64, mpert, mpert, 6)
        block_t = zeros(ComplexF64, mpert, mpert, 6)
        for psi in PSI_SURFACES
            psi_group = create_group(h5, @sprintf("psi=%.3f", psi))
            attributes(psi_group)["psi"] = psi
            t_psi0 = time()
            fill!(block_w, 0); fill!(block_t, 0)
            compute_kinetic_matrices_at_psi!(
                block_w, block_t,
                Float64(psi), NN, ELL,
                state.kf_ctrl.zi, state.kf_ctrl.mi,
                state.kf_ctrl.wdfac, state.kf_ctrl.divxfac,
                state.kf_ctrl.electron,
                state.equil, state.kf_intr, state.kinetic_profiles;
                pitch_integrator)

            # "full" = kw + kt = energy (imag) + torque (real)
            full = block_w .+ block_t
            for (k, name) in enumerate(("Ak", "Bk", "Ck", "Dk", "Ek", "Hk"))
                write(psi_group, name, full[:, :, k])
            end
            per_surface_wall[psi] = time() - t_psi0
            attributes(psi_group)["wall_time_s"] = per_surface_wall[psi]
            @printf(stderr, "  ψ=%.2f:  wall = %6.2f s\n", psi, per_surface_wall[psi])
        end

        total_wall = time() - total_t0
        attributes(h5)["total_wall_s"] = total_wall
        attributes(h5)["setup_wall_s"] = t_setup
        @printf(stderr, "  ------------------------------\n")
        @printf(stderr, "  matrix loop:     %6.2f s\n", total_wall)
        @printf(stderr, "  wrote %s\n", out_h5)
    end
    println(stderr, "=" ^ 70)

    return (; out_h5, per_surface_wall, setup_wall=t_setup)
end

if abspath(PROGRAM_FILE) == @__FILE__
    fortran_dir = length(ARGS) >= 1 ? ARGS[1] : DEFAULT_FORTRAN_DIR
    out_h5 = length(ARGS) >= 2 ? ARGS[2] : DEFAULT_OUT_H5
    pitch_integrator = length(ARGS) >= 3 ? Symbol(ARGS[3]) : :ode
    dump_matrices(fortran_dir, out_h5; pitch_integrator)
end
