"""
    VacuumInput

Struct holding plasma boundary and mode data as provided from ForceFreeStates namelist and computed quantities.
For an axisymmetric boundary, nzeta_in = 1 and only the x and z arrays need to be provided - the code can then
be run with nzeta = 1 for 2D vacuum calculation or nzeta > 1 for 3D vacuum calculation. For a non-axisymmetric boundary,
nzeta_in > 1 and the x, y, and z arrays need to be provided - the code can then be run with nzeta = 1 for 2D vacuum calculation or
nzeta > 1 for 3D vacuum calculation. The arrays should be for a single field period only, with excluded endpoints.

# Fields

  - `x::Vector{Float64}`: Plasma boundary X-coordinate (length mtheta_in * nzeta_in)
  - `y::Vector{Float64}`: Plasma boundary Y-coordinate (length mtheta_in * nzeta_in)
  - `z::Vector{Float64}`: Plasma boundary Z-coordinate (length mtheta_in * nzeta_in)
  - `ν::Vector{Float64}`: Free parameter in specifying toroidal angle, ζ = ϕ + ν(θ), on input theta grid (axisymmetric only, length mtheta_in)
  - `mtheta_in::Int`: Number of input poloidal grid points
  - `nzeta_in::Int`: Number of input toroidal grid points (1 for axisymmetric, > 1 for non-axisymmetric)
  - `m_modes::Vector{Int}`: Vector of poloidal mode numbers. E.g. `collect(mlow:mhigh)` for a contiguous range.
  - `n_modes::Vector{Int}`: Vector of toroidal mode numbers. E.g. `collect(nlow:nhigh)` for a contiguous range or `collect(nlow:n_stride:nhigh)` for a strided list for stellarator mode-family calculations.
  - `mtheta::Int`: Number of vacuum calculation poloidal grid points
  - `nzeta::Int`: Number of vacuum calculation toroidal grid points (1 for 2D vacuum calculation, > 1 for 3D vacuum calculation)
  - `nfp::Int`: Number of field periods
"""
@kwdef struct VacuumInput
    x::Vector{Float64} = Float64[]
    y::Vector{Float64} = Float64[]
    z::Vector{Float64} = Float64[]
    ν::Vector{Float64} = Float64[]
    mtheta_in::Int = 0
    nzeta_in::Int = 1
    m_modes::Vector{Int} = [1]
    n_modes::Vector{Int} = [1]
    mtheta::Int = 1
    nzeta::Int = 1
    nfp::Int = 1
end

"""
    VacuumInput(
        equil::Equilibrium.PlasmaEquilibrium,
        ψ::Float64,
        mtheta::Int,
        nzeta::Int,
        m_modes::AbstractVector{<:Integer},
        n_modes::AbstractVector{<:Integer};
    ) -> VacuumInput

Constructor to create a VacuumInput struct for computing Green's functions at arbitrary flux surface.
Extracts plasma geometry from equilibrium at the given flux surface and packages it into VacuumInput format.

## Arguments

  - `equil`: Equilibrium solution
  - `ψ`: Normalized flux coordinate
  - `mtheta`: Number of vacuum calculation poloidal points
  - `nzeta`: Number of vacuum calculation toroidal points (1 for 2D, >1 for 3D)
  - `m_modes`: Poloidal mode numbers (e.g. `mlow:mhigh`)
  - `n_modes`: Toroidal mode numbers (e.g. `[n]` for a single mode, or `nlow:nhigh`)

## Returns

VacuumInput structure ready for compute_vacuum_response()
"""
function VacuumInput(
    equil::Equilibrium.PlasmaEquilibrium,
    ψ::Float64,
    mtheta::Int,
    nzeta::Int,
    m_modes::AbstractVector{<:Integer},
    n_modes::AbstractVector{<:Integer}
)
    # Extract plasma surface geometry at this psi
    r, z, ν = extract_plasma_surface_at_psi(equil, ψ)

    # Remove the last point to go from the [0, 2π] grid to VACUUM's [0, 2π) grid
    # and reverse the arrays for VACUUM's CW θ direction (θ_VAC = -θ_GPEC). This handedness is why
    # operators returned to GPEC (e.g. the surface-inductance current matrix) are conjugated.
    return VacuumInput(;
        x=reverse(r)[1:(end-1)],
        z=reverse(z)[1:(end-1)],
        ν=reverse(ν)[1:(end-1)],
        mtheta_in=length(r)-1,
        m_modes=collect(Int, m_modes),
        n_modes=collect(Int, n_modes),
        mtheta=mtheta,
        nzeta=nzeta
    )
end

"""
    expand_field_periods(inputs::VacuumInput) -> VacuumInput

Reconstruct the full-torus boundary from a single field period using the device field
periodicity. When `inputs.nfp > 1` (and the boundary is 3D), the input `x, y, z` arrays
describe one field period spanning ζ ∈ [0, 2π/nfp) on an `mtheta_in × nzeta_in` grid; the
full torus is generated by `nfp` rigid rotations about the Z-axis by 2π·k/nfp. The toroidal
counts `nzeta_in` and `nzeta` are scaled to their full-torus totals and `nfp` is reset to 1,
so all downstream code operates on the full surface unchanged.

This is the layer-1 interface: it shrinks the Python→Julia payload to one field period while
producing a full-torus geometry identical (to floating-point) to sending the whole torus.

Returns `inputs` unchanged for axisymmetric (`nzeta_in == 1`) or single-period (`nfp <= 1`) cases.
"""
function expand_field_periods(inputs::VacuumInput)
    (inputs.nfp <= 1 || inputs.nzeta_in <= 1) && return inputs

    nfp = inputs.nfp
    mt = inputs.mtheta_in
    nz = inputs.nzeta_in   # points per field period
    npts = mt * nz
    @assert length(inputs.x) == length(inputs.y) == length(inputs.z) == npts "per-period x, y, z must have length mtheta_in * nzeta_in"

    nz_full = nz * nfp
    xf = Vector{Float64}(undef, mt * nz_full)
    yf = similar(xf)
    zf = similar(xf)

    # Tile to full torus: period k is the single period rotated by α = 2π·k/nfp about Z.
    for k in 0:(nfp-1)
        α = 2π * k / nfp
        ca, sa = cos(α), sin(α)
        @inbounds for j in 1:nz, i in 1:mt
            src = i + mt * (j - 1)
            dst = i + mt * (j - 1 + k * nz)
            xf[dst] = inputs.x[src] * ca - inputs.y[src] * sa
            yf[dst] = inputs.x[src] * sa + inputs.y[src] * ca
            zf[dst] = inputs.z[src]
        end
    end

    return VacuumInput(;
        x=xf,
        y=yf,
        z=zf,
        ν=inputs.ν,
        mtheta_in=mt,
        nzeta_in=nz_full,
        m_modes=inputs.m_modes,
        n_modes=inputs.n_modes,
        mtheta=inputs.mtheta,
        nzeta=inputs.nzeta * nfp,
        nfp=1
    )
end

"""
    VacuumResponse

Output of [`compute_vacuum_response`](@ref): the vacuum energy matrix and the surface data the
boundary-integral solve produces along the way.

## Fields

  - `wv::Matrix{ComplexF64}`: Vacuum energy matrix Wᵛ (`num_modes × num_modes`), block-diagonal in n for 2D
  - `I_v::Matrix{ComplexF64}`: Vacuum surface-current matrix Iᵛ (`num_modes × num_modes`), left zeroed
    unless `compute_vacuum_response` is called with `compute_Iv=true` (2D only). Stored without the
    `μ₀`/`4π²` normalization: the physical surface inductance is `μ₀(2π)²·I_v⁻¹`
    (see `PerturbedEquilibrium.calc_surface_inductance`).
  - `plasma_pts`, `wall_pts::Matrix{Float64}`: Cartesian surface coordinates (`num_points × 3`)
"""
struct VacuumResponse
    wv::Matrix{ComplexF64}
    I_v::Matrix{ComplexF64}
    plasma_pts::Matrix{Float64}
    wall_pts::Matrix{Float64}
end

"""
    VacuumResponse(inputs::VacuumInput) -> VacuumResponse

Allocate zeroed output arrays sized for `inputs` (full torus, so `nfp` field periods).
"""
function VacuumResponse(inputs::VacuumInput)
    num_points = inputs.mtheta * inputs.nzeta * inputs.nfp
    num_modes = length(inputs.m_modes) * length(inputs.n_modes)
    return VacuumResponse(
        zeros(ComplexF64, num_modes, num_modes),
        zeros(ComplexF64, num_modes, num_modes),
        zeros(num_points, 3),
        zeros(num_points, 3)
    )
end

"""
    WallShapeSettings

Struct containing input settings for vacuum wall geometry.

# Fields

  - `shape::String`: String selecting wall shape. Options are:

        + `"nowall"`: No wall
        + `"conformal"`: Wall conformal to plasma surface at distance `a`
        + `"elliptical"`: Elliptical wall
        + `"dee"`: Dee-shaped wall
        + `"mod_dee"`: Modified Dee-shaped wall
        + `"filepath"`: Custom wall shape from the file you specify

    A non-axisymmetric boundary (`nzeta_in > 1`) supports `"nowall"` and `"conformal"`; the others
    are poloidal contours that get revolved and so need `nzeta_in == 1`.

  - `a::Float64`: Distance of wall from plasma in units of major radius (conformal), or shape parameter (others)

  - `aw::Float64`: Half-thickness parameter for Dee-shaped walls

  - `bw::Float64`: Elongation parameter for wall shapes

  - `cw::Float64`: Offset of the center of the wall from the major radius

  - `dw::Float64`: Triangularity parameter for wall shapes

  - `tw::Float64`: Sharpness of the corners of the wall (try 0.05 as initial value)

    # Core shape selection

  - `equal_arc_wall::Bool`: Flag to enforce equal arc length distribution of nodes on the wall
    (recommended unless wall is very close to plasma). Re-parameterizing the contour breaks the
    plasma/wall grid index correspondence that the singular quadrature relies on; it is ignored
    outright for `nzeta_in > 1` walls.
"""
@kwdef struct WallShapeSettings

    # Core shape selection
    shape::String = "nowall"

    # Standard geometric parameters for Dee/Mod-Dee
    a::Float64 = 0.3
    aw::Float64 = 0.05
    bw::Float64 = 1.5
    cw::Float64 = 0.0
    dw::Float64 = 0.5
    tw::Float64 = 0.05

    # Algorithmic options
    equal_arc_wall::Bool = true
end

"""
    PlasmaGeometry

Struct holding plasma geometry data on the mtheta grid for vacuum calculations. Arrays are
of length `mtheta`, where `mtheta` is the number of poloidal grid points and θ ∈ [0, 1).

# Fields

  - `x::Vector{Float64}`: Plasma surface R-coordinate on VACUUM theta grid
  - `z::Vector{Float64}`: Plasma surface Z-coordinate on VACUUM theta grid
  - `ν::Vector{Float64}`: Magnetic toroidal angle offset from geometric toroidal angle
"""
struct PlasmaGeometry
    x::Vector{Float64}
    z::Vector{Float64}
    ν::Vector{Float64}
end

"""
    WallGeometry

Struct holding wall geometry data for vacuum calculations. Arrays are of length
`mtheta`, where `mtheta` is the number of poloidal grid points and θ ∈ [0, 1).

# Fields

  - `nowall::Bool`: Boolean flag indicating if there is no wall
  - `x::Vector{Float64}`: Wall R-coordinates
  - `z::Vector{Float64}`: Wall Z-coordinates
"""
struct WallGeometry
